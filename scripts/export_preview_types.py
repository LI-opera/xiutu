"""Generate browser types from the exact opt-in app OpenAPI, without DB connection."""
import json
from pathlib import Path
from app.config import Settings
from app.legacy_preview.product import create_preview

ROOT = Path(__file__).resolve().parents[1]
app = create_preview(Settings(app_mode="test", retrieval_profile="synthetic", database_url="postgresql://schema:unused@127.0.0.1:5433/xiutu_test_preview_schema", deepseek_api_key=None))
schema = app.openapi()

def ts(s):
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1].replace("-", "_")
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    if "enum" in s:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in s["enum"])
    if "anyOf" in s or "oneOf" in s:
        return "(" + " | ".join(ts(x) for x in s.get("anyOf", s.get("oneOf"))) + ")"
    t = s.get("type")
    if t == "array": return "Array<" + ts(s.get("items", {})) + ">"
    if t == "object" or "properties" in s:
        props=s.get("properties", {})
        if not props: return "Record<string, unknown>"
        return "{ " + "; ".join(json.dumps(k)+("" if k in s.get("required", []) else "?")+": "+ts(v) for k,v in props.items()) + " }"
    return {"string":"string", "integer":"number", "number":"number", "boolean":"boolean", "null":"null"}.get(t, "unknown")

out="// GENERATED by scripts/export_preview_types.py; do not hand-edit.\n"
for name, obj in schema["components"]["schemas"].items():
    out += "export type " + name.replace("-", "_") + " = " + ts(obj) + ";\n"
(ROOT/"frontend/src/api-schema.ts").write_text(out,encoding="utf-8")
(ROOT/"docs/implementation/product-preview/openapi.json").write_text(json.dumps(schema,ensure_ascii=False,indent=2),encoding="utf-8")
print("Exported preview OpenAPI and TypeScript schemas")
